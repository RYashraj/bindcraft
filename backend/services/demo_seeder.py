def _write_demo_mdout(output_dir: Path) -> None:
    """Generate a realistic-looking minimal mdout for production stage."""
    lines = [
        "          -------------------------------------------------------",
        "          Amber 22 SANDER                              2022",
        "          -------------------------------------------------------",
        "",
        "| PMEMD implementation of SANDER, Release 22",
        "",
        " NSTEP =    500   TIME(PS) =    1.000  TEMP(K) =  299.8  PRESS =    -24.5",
        " Etot   =   -48234.5678  EKtot   =    9123.4567  EPtot      =   -57358.0245",
        " BOND   =      345.6789  ANGLE   =      567.8901  DIHED      =     1234.5678",
        "",
    ]
    # Generate 50 frames of synthetic data
    for i in range(1, 51):
        nstep = i * 500
        time = i * 1.0
        temp = 300.0 + 2.0 * math.sin(i * 0.3) + random.gauss(0, 0.5)
        eptot = -57000.0 - 200 * math.exp(-i * 0.05) + random.gauss(0, 50)
        lines += [
            f" NSTEP = {nstep:6d}   TIME(PS) = {time:8.3f}  TEMP(K) = {temp:6.2f}  PRESS =   {random.uniform(-50, 50):.1f}",
            f" Etot   = {eptot + 9000:12.4f}  EKtot   =   9134.2345  EPtot      = {eptot:12.4f}",
            f" BOND   =    {random.uniform(300, 400):.4f}  ANGLE   =    {random.uniform(500, 650):.4f}  DIHED      =   {random.uniform(1200, 1300):.4f}",
            "",
        ]
    (output_dir / "prod.mdout").write_text("\n".join(lines), encoding="utf-8")


