def _write_demo_analysis(analysis_dir: Path) -> None:
    """Write synthetic but realistic RMSD, RMSF, Rg CSVs."""
    random.seed(42)

    # RMSD — slowly rises then plateaus around 2.5 Å
    with open(analysis_dir / "rmsd.csv", "w") as f:
        f.write("#Frame,RMSD\n")
        for i in range(1, 51):
            rmsd = 2.5 * (1 - math.exp(-i * 0.08)) + random.gauss(0, 0.05)
            f.write(f"{i},{max(0, rmsd):.4f}\n")

    # RMSF — per residue (50 residues)
    with open(analysis_dir / "rmsf.csv", "w") as f:
        f.write("#Residue,RMSF\n")
        for i in range(1, 51):
            # Loop regions have higher RMSF
            base = 0.8 if (10 <= i <= 15 or 35 <= i <= 40) else 0.4
            rmsf = base + random.gauss(0, 0.1)
            f.write(f"{i},{max(0, rmsf):.4f}\n")

    # Rg — radius of gyration, slightly decreasing as system compacts
    with open(analysis_dir / "rg.csv", "w") as f:
        f.write("#Frame,Rg\n")
        for i in range(1, 51):
            rg = 22.5 - 0.5 * (1 - math.exp(-i * 0.06)) + random.gauss(0, 0.1)
            f.write(f"{i},{rg:.4f}\n")


