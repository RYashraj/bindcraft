"""
Demo seeder — creates a realistic fake completed project in the database
and populates its directory with pre-built files.

This runs once at startup and is idempotent.
"""
from __future__ import annotations

import json
import logging
import math
import random
from datetime import datetime
from pathlib import Path

from backend.config import settings
from backend.models import Project, Job

logger = logging.getLogger("bindcraft.demo")

DEMO_PROJECT_ID = "demo-acetylcholinesterase"
DEMO_JOB_ID = "demo-job-001"


def seed_demo_project() -> None:
    """Insert the demo project if it does not already exist."""
    from backend.database import SessionLocal

    db = SessionLocal()
    try:
        existing = db.query(Project).filter(Project.id == DEMO_PROJECT_ID).first()
        if existing:
            return  # Already seeded

        logger.info("Seeding demo project...")
        _create_files()

        project = Project(
            id=DEMO_PROJECT_ID,
            name="Demo: Acetylcholinesterase + Donepezil",
            notes=(
                "This is a pre-built demonstration project simulating the binding of "
                "donepezil (Aricept) to human acetylcholinesterase — a classic example "
                "in pharmacology education. The data is synthetic but realistic."
            ),
            pdb_filename="ache_donepezil_complex.pdb",
            ligand_filename="donepezil.sdf",
            ligand_name="DPZ",
            ligand_charge=1,
            status="completed",
            settings_json=json.dumps({
                "protein_ff": "ff14SB",
                "ligand_ff": "GAFF2",
                "water_model": "TIP3P",
                "solvent_type": "explicit",
                "box_padding": 10.0,
                "temperature": 300.0,
                "pressure": 1.0,
                "preset": "fast_test",
                "output_freq": 500,
            }),
        )
        db.add(project)

        job = Job(
            id=DEMO_JOB_ID,
            project_id=DEMO_PROJECT_ID,
            mode="run",
            status="success",
            current_step="Complete",
            started_at=datetime(2025, 6, 15, 10, 0, 0),
            finished_at=datetime(2025, 6, 15, 10, 23, 45),
        )
        db.add(job)
        db.commit()
        logger.info("Demo project seeded successfully.")
    except Exception as exc:
        db.rollback()
        logger.error("Failed to seed demo project: %s", exc)
    finally:
        db.close()


def _create_files() -> None:
    """Write all demo data files."""
    base = settings.project_path(DEMO_PROJECT_ID)
    for sub in ("input", "output", "logs", "analysis", "report"):
        (base / sub).mkdir(parents=True, exist_ok=True)

    _write_demo_pdb(base / "input" / "ache_donepezil_complex.pdb")
    _write_demo_sdf(base / "input" / "donepezil.sdf")
    _write_demo_tleap(base / "input")
    _write_demo_mdins(base / "input")
    _write_demo_cpptraj(base / "input")
    _write_demo_mdout(base / "output")
    _write_demo_log(base / "logs" / f"{DEMO_JOB_ID}.log")
    _write_demo_analysis(base / "analysis")
    _write_demo_report(base / "report")


